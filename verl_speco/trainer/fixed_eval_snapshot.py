"""Persist fixed rollout trajectories without changing online training selection."""

import gzip
import hashlib
import json
import os
import tempfile
from collections import defaultdict
from pathlib import Path

import numpy as np
import torch


def _json_default(value):
    if torch.is_tensor(value):
        return value.detach().cpu().tolist()
    if isinstance(value, np.ndarray):
        return value.tolist()
    if isinstance(value, np.generic):
        return value.item()
    raise TypeError(f"Unsupported fixed-eval metadata type: {type(value).__name__}")


def _digest(value):
    return hashlib.sha256(json.dumps(value, separators=(",", ":")).encode()).hexdigest()


def export_fixed_eval_snapshot(
    batch, *, collect_mask, root, step, sample_count, seed, actor_checkpoint,
    experiment_id, run_id, rollout_config=None,
):
    """Save full unpadded tokens and proposal traces, excluding collected rows.

    The actor checkpoint must represent step-1: this hook runs before the actor
    update, and the batch was generated by that same pre-update policy.
    """
    if step < 1 or sample_count < 1:
        raise ValueError("Fixed eval step and sample_count must be positive")
    destination = Path(root) / f"step_{step}"
    manifest_path = destination / "manifest.json"
    if manifest_path.is_file():
        manifest = json.loads(manifest_path.read_text())
        if manifest["run_id"] != run_id or manifest["rollout_step"] != step:
            raise ValueError("Fixed eval snapshot belongs to a different run or step")
        if not (destination / manifest["samples_file"]).is_file():
            raise ValueError("Fixed eval snapshot manifest has no sample file")
        return manifest
    actor_checkpoint = Path(actor_checkpoint)
    if not actor_checkpoint.is_dir():
        raise ValueError(f"Fixed eval requires the pre-update actor checkpoint: {actor_checkpoint}")
    tensors = batch.batch
    prompts, responses = tensors["prompts"], tensors["responses"]
    attention = tensors["attention_mask"]
    collected = collect_mask.detach().cpu().bool().reshape(-1)
    if collected.numel() != prompts.size(0):
        raise ValueError("Fixed eval collection mask does not match rollout batch")
    groups = defaultdict(list)
    for index in range(prompts.size(0)):
        if bool(collected[index]):
            continue
        prompt = prompts[index][attention[index, :prompts.size(1)].bool()].detach().cpu().tolist()
        response_valid = attention[index, prompts.size(1):prompts.size(1) + responses.size(1)].bool()
        response = responses[index][response_valid].detach().cpu().tolist()
        if not prompt or not response:
            continue
        prompt_id = _digest(prompt)
        sample_id = _digest([step, prompt, response, index])
        groups[prompt_id].append((
            _digest([seed, step, sample_id]), index, prompt, response, response_valid, sample_id,
        ))
    group_order = sorted(groups, key=lambda key: _digest([seed, step, key]))
    for values in groups.values():
        values.sort(key=lambda value: value[0])
    selected = []
    # Round-robin across prompts so five answers to one prompt do not crowd out
    # distinct problems. Selection does not depend on reward or acceptance.
    for depth in range(max((len(values) for values in groups.values()), default=0)):
        for key in group_order:
            if depth < len(groups[key]) and len(selected) < sample_count:
                selected.append((key, groups[key][depth]))
        if len(selected) >= sample_count:
            break
    if not selected:
        raise ValueError("No uncollected rollout samples available for fixed evaluation")

    destination.mkdir(parents=True, exist_ok=True)
    file_digest = hashlib.sha256()
    non_tensors = getattr(batch, "non_tensor_batch", {}) or {}
    fd, temporary_name = tempfile.mkstemp(prefix="samples-", suffix=".tmp", dir=destination)
    os.close(fd)
    try:
        with gzip.open(temporary_name, "wt", encoding="utf-8", compresslevel=1) as stream:
            for prompt_id, (_, index, prompt, response, valid, sample_id) in selected:
                row = {
                    "sample_id": sample_id, "prompt_id": prompt_id, "batch_index": index,
                    "rollout_step": step, "actor_snapshot_step": step - 1,
                    "prompt_token_ids": prompt, "response_token_ids": response,
                    "excluded_from_source_drafter_training": True,
                }
                response_mask = tensors.get("response_mask")
                if response_mask is not None:
                    row["response_loss_mask"] = response_mask[index][valid].detach().cpu().tolist()
                for key in ("uid", "data_source", "reward_model", "speculative_trace", "speculative_trace_diagnostics"):
                    values = non_tensors.get(key)
                    if values is not None and index < len(values):
                        row[key] = values[index]
                for key in ("token_level_scores", "token_level_rewards"):
                    values = tensors.get(key)
                    if values is not None:
                        row[key + "_sum"] = float(values[index].detach().float().sum().cpu())
                serialized = json.dumps(row, default=_json_default, ensure_ascii=True, allow_nan=False, separators=(",", ":")) + "\n"
                file_digest.update(serialized.encode())
                stream.write(serialized)
        os.replace(temporary_name, destination / "samples.jsonl.gz")
    finally:
        if os.path.exists(temporary_name):
            os.unlink(temporary_name)
    manifest = {
        "format_version": 1, "experiment_id": experiment_id, "run_id": run_id,
        "rollout_step": step, "actor_snapshot_step": step - 1,
        "phase": "after_rollout_before_actor_update",
        "actor_checkpoint": str(actor_checkpoint.resolve()),
        "requested_samples": sample_count, "sample_count": len(selected),
        "unique_prompts": len({key for key, _ in selected}),
        "source_batch_size": int(prompts.size(0)),
        "excluded_drafter_collection_samples": int(collected.sum()),
        "sample_indices": [value[1] for _, value in selected],
        "selection_seed": seed, "samples_file": "samples.jsonl.gz",
        "uncompressed_sha256": file_digest.hexdigest(),
        "rollout_config": rollout_config or {},
        "evaluation_scope": "fixed trajectories/prefixes; recompute features with the recorded actor snapshot",
        "holdout_scope": "excluded from source drafter collection; still part of actor PPO and DAPO training",
    }
    fd, temporary_manifest = tempfile.mkstemp(prefix="manifest-", suffix=".tmp", dir=destination)
    try:
        with os.fdopen(fd, "w", encoding="utf-8") as stream:
            json.dump(manifest, stream, indent=2, allow_nan=False)
            stream.write("\n")
        os.replace(temporary_manifest, manifest_path)
    finally:
        if os.path.exists(temporary_manifest):
            os.unlink(temporary_manifest)
    return manifest
