#!/usr/bin/env bash
set -euo pipefail

# Physical Ascend cards 4-7 expose logical devices 8-15 on this host.
# Preview: DRY_RUN=1 DSPARK_TOPK_ARM=response bash tools/run_dspark_topk_half_node.sh
PROJECT_ROOT=$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)
arm=${DSPARK_TOPK_ARM:-response}
case "${arm}" in
    k3)       response_loss=k3;   rejected_loss=k3 ;;
    response) response_loss=topk; rejected_loss=k3 ;;
    rejected) response_loss=k3;   rejected_loss=topk ;;
    both)     response_loss=topk; rejected_loss=topk ;;
    *) echo "DSPARK_TOPK_ARM must be k3, response, rejected, or both" >&2; exit 2 ;;
esac
if [[ -n "${ASCEND_RT_VISIBLE_DEVICES:-}" && "${ASCEND_RT_VISIBLE_DEVICES}" != 8,9,10,11,12,13,14,15 ]]; then
    echo "This profile requires logical devices 8-15 (physical cards 4-7)." >&2
    exit 2
fi
export ASCEND_RT_VISIBLE_DEVICES=8,9,10,11,12,13,14,15
export N_GPUS=8 DRAFT_WORKER_WORLD_SIZE=8 GEN_TP_SIZE=4 TRAIN_SP_SIZE=4
export SPECO_SKIP_GLOBAL_RAY_STOP=1 RAY_ADDRESS=local
export RUN_MODE=online DATASET_PROFILE=dapo
export SPECO_ONLINE_STRATEGY_TAG=${SPECO_ONLINE_STRATEGY_TAG:-p2_02_swa512_top16_${arm}_half}
export TOTAL_STEPS=${TOTAL_STEPS:-101} SAVE_FREQ=10 SAVE_OFFSET=9
export TRAIN_BATCH_SIZE=64 ROLLOUT_N=5 PPO_MINI_BATCH_SIZE=16
export PPO_MICRO_BATCH_SIZE_PER_GPU=${PPO_MICRO_BATCH_SIZE_PER_GPU:-10}
export MAX_PROMPT_LENGTH=512 MAX_RESPONSE_LENGTH=8192
export MAX_NUM_SEQS=${MAX_NUM_SEQS:-128} MAX_NUM_BATCHED_TOKENS=${MAX_NUM_BATCHED_TOKENS:-16384}
export GPU_MEMORY_UTILIZATION=${GPU_MEMORY_UTILIZATION:-0.5}
export DRAFTER_INIT_CHECKPOINT=${DRAFTER_INIT_CHECKPOINT:-}
export DRAFTER_INIT_IS_STRONG=false
export DRAFT_TRAIN_STEPS=${DRAFT_TRAIN_STEPS:-5} DRAFT_COLLECT_INTERVAL_STEPS=5 DRAFT_TRAINING_INTERVAL_STEPS=5
export DRAFT_LR=1e-5 DRAFT_LR_SCHEDULER_TYPE=constant DRAFT_LR_WARMUP_STEPS=0
# Half as many TP replicas: preserve global batch, collection budget and eval cohort.
export DRAFT_BATCH_SIZE_PER_GPU=8 DRAFT_TRAIN_BATCHES_PER_CYCLE=4
export DRAFT_MAX_COLLECT_SAMPLES_PER_REPLICA=${DRAFT_MAX_COLLECT_SAMPLES_PER_REPLICA:-40}
export DRAFT_MAX_COLLECT_TOKENS_PER_REPLICA=${DRAFT_MAX_COLLECT_TOKENS_PER_REPLICA:-32768}
export DRAFT_FIXED_EVAL_SAMPLES_PER_REPLICA=8 DRAFT_TRAIN_UNIQUE_SAMPLES_FIRST=true
export DSPARK_RESPONSE_LOSS=${response_loss} DSPARK_REJECTED_LOSS=${rejected_loss} DSPARK_TOPK=16
export DSPARK_TRACE_ALIGNED_ANCHORS=True
export DSPARK_USE_ABSOLUTE_POSITION_IDS=${DSPARK_USE_ABSOLUTE_POSITION_IDS:-True}
export DSPARK_VLLM_ATTENTION_MODE=${DSPARK_VLLM_ATTENTION_MODE:-swa}
export DSPARK_VLLM_CONTEXT_WINDOW=${DSPARK_VLLM_CONTEXT_WINDOW:-512}
export DSPARK_TRAINING_ATTENTION_MODE=${DSPARK_TRAINING_ATTENTION_MODE:-swa}
export DSPARK_TRAINING_CONTEXT_WINDOW=${DSPARK_TRAINING_CONTEXT_WINDOW:-512}
export DSPARK_TRAINING_MAX_WINDOW=${DSPARK_TRAINING_MAX_WINDOW:-1024}
export DSPARK_COLLECTION_WINDOW=${DSPARK_COLLECTION_WINDOW:-1024}
export DSPARK_LOSS_DECAY_GAMMA=0 DSPARK_CE_LOSS_ALPHA=0 DSPARK_L1_LOSS_ALPHA=0
export DSPARK_ACCEPTED_K3_ALPHA=1 DSPARK_ACCEPTED_FKL_ALPHA=0 DSPARK_REJECTED_K3_ALPHA=1
export DSPARK_RESPONSE_STREAM_WEIGHT=1 DSPARK_REJECTED_STREAM_WEIGHT=0.5 DSPARK_REJECTED_POSITION_DECAY=0.8
export DSPARK_ASYMMETRIC_K3_ENABLED=false DSPARK_ACCEPTED_ASYMMETRIC_K3_ENABLED=false
export DSPARK_REJECTED_ASYMMETRIC_K3_ENABLED=false DSPARK_DYNAMIC_ACCEPT_REJECT_WEIGHTING_ENABLED=false
export DSPARK_DUMP_K3_LOGPROBS=${DSPARK_DUMP_K3_LOGPROBS:-true}
export DSPARK_POST_UPDATE_MEAN_ACCEPTANCE_LENGTH_DROP_ABORT_THRESHOLD=0.5
export DRAFT_DUAL_METRIC_BEST_CHECKPOINT_ENABLED=true SAVE_BEST_DRAFTER_CHECKPOINT=true
export DELETE_CHECKPOINTS_AFTER_SUCCESS=0

exec bash "${PROJECT_ROOT}/tools/run_dspark_vllm_experiment.sh" "$@"
